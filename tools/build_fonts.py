"""Subsets the game fonts to the characters actually used and writes src/fonts.css with the fonts
embedded (works from file:// too). Run from tools/build.mjs.

GameFont = Fredoka SemiBold for Latin/digits + Jua for Hangul (same family name, split by
unicode-range, so the browser picks per character)."""
import base64, glob, io, json, os, sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
FONTS = os.path.join(ROOT, 'art', 'fonts')

chars = set(chr(c) for c in range(0x20, 0x7f))
chars |= set('·…—–’‘“”•×→←↑↓%°!?~')
for f in glob.glob(os.path.join(ROOT, 'src', 'i18n', '*.json')):
    for v in json.load(open(f, encoding='utf-8')).values():
        chars |= set(v)
for f in glob.glob(os.path.join(ROOT, 'src', 'data', 'levels', '*.json')) + [os.path.join(ROOT, 'src', 'data', 'island-specs.json')]:
    chars |= set(open(f, encoding='utf-8').read())
extra = os.path.join(ROOT, 'src', 'data', 'font-extra.txt')
if os.path.exists(extra):
    chars |= set(open(extra, encoding='utf-8').read())
# generated names for endless islands etc.
chars |= set('끝없는하늘 0123456789')
hangul = sorted(c for c in chars if '가' <= c <= '힣' or '㄰' <= c <= '㆏')
latin = sorted(c for c in chars if ord(c) < 0x2500 and not ('가' <= c <= '힣'))

def make(src, text, out_name, var=None):
    font = TTFont(src)
    if var:
        font = instancer.instantiateVariableFont(font, var)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(options=opts)
    sub.populate(text=''.join(text))
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    data = buf.getvalue()
    os.makedirs(os.path.join(ROOT, 'out', 'assets', 'fonts'), exist_ok=True)
    open(os.path.join(ROOT, 'out', 'assets', 'fonts', out_name), 'wb').write(data)
    return data

lat = make(os.path.join(FONTS, 'Fredoka.ttf'), latin, 'game-latin.woff2', {'wght': 600, 'wdth': 100})
ko = make(os.path.join(FONTS, 'Jua-Regular.ttf'), hangul + latin, 'game-ko.woff2')
css = f"""/* generated by tools/build_fonts.py — Fredoka (Latin) + Jua (Hangul), SIL OFL 1.1 */
@font-face {{ font-family: 'GameFont'; src: url(data:font/woff2;base64,{base64.b64encode(lat).decode()}) format('woff2'); unicode-range: U+0000-024F, U+2000-206F, U+20AC, U+2190-21FF; font-display: block; }}
@font-face {{ font-family: 'GameFont'; src: url(data:font/woff2;base64,{base64.b64encode(ko).decode()}) format('woff2'); unicode-range: U+1100-11FF, U+3130-318F, U+AC00-D7A3, U+00B7, U+2026; font-display: block; }}
"""
open(os.path.join(ROOT, 'src', 'fonts.css'), 'w').write(css)
print(f'fonts: latin {len(latin)} glyphs {len(lat)//1024}KB, hangul {len(hangul)} glyphs {len(ko)//1024}KB')
