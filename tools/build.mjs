// Build: bundles src/ into out/ (production + dev builds), copies static assets.
//   node tools/build.mjs          -> out/index.html (prod) + out/dev/index.html (dev, debug panel)
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'out');
const watch = process.argv.includes('--watch');

function copyDir(src, dst) {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'))).version;
const stamp = Date.now().toString(36);

function writeLevelIndex() {
  const dir = path.join(root, 'src/data/levels');
  const files = fs.readdirSync(dir).filter((f) => /^island\d+\.json$/.test(f)).sort();
  const lines = ['// Generated by tools/build.mjs from src/data/levels/*.json. Do not edit by hand.'];
  files.forEach((f, i) => lines.push(`import L${i} from './levels/${f}';`));
  lines.push(`export const LEVELS = [${files.map((_, i) => 'L' + i).join(', ')}];`);
  const text = lines.join('\n') + '\n';
  const target = path.join(root, 'src/data/levels.js');
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) fs.writeFileSync(target, text);
}

import { execSync } from 'node:child_process';

async function buildAll() {
  writeLevelIndex();
  // fonts (subset to used glyphs) + atlas metadata into the bundle
  execSync('python3 tools/build_fonts.py', { cwd: root, stdio: 'inherit' });
  if (fs.existsSync(path.join(out, 'assets/atlas.json'))) fs.copyFileSync(path.join(out, 'assets/atlas.json'), path.join(root, 'src/data/atlas.json'));
  const common = {
    entryPoints: [path.join(root, 'src/main.js')],
    bundle: true,
    format: 'iife',
    target: ['es2019', 'safari13'],
    loader: { '.json': 'json' },
    legalComments: 'none',
    logLevel: 'warning',
  };
  await esbuild.build({
    ...common,
    outfile: path.join(out, 'game.js'),
    minify: true,
    define: { __DEV__: 'false', __VERSION__: JSON.stringify(version) },
    drop: ['debugger'],
  });
  await esbuild.build({
    ...common,
    outfile: path.join(out, 'dev/game.js'),
    minify: false,
    sourcemap: 'inline',
    define: { __DEV__: 'true', __VERSION__: JSON.stringify(version + '-dev') },
  });
  // editor bundle
  if (fs.existsSync(path.join(root, 'src/editor/editor.js'))) {
    await esbuild.build({
      ...common,
      entryPoints: [path.join(root, 'src/editor/editor.js')],
      outfile: path.join(out, 'editor/editor.js'),
      minify: false,
      define: { __DEV__: 'true', __VERSION__: JSON.stringify(version) },
    });
    let ehtml = fs.readFileSync(path.join(root, 'src/editor/editor.html'), 'utf8');
    fs.writeFileSync(path.join(out, 'editor/index.html'), ehtml.replace(/__STAMP__/g, stamp));
  }
  const html = fs.readFileSync(path.join(root, 'src/index.html'), 'utf8');
  fs.writeFileSync(path.join(out, 'index.html'), html.replace(/__STAMP__/g, stamp).replace(/__BASE__/g, ''));
  fs.mkdirSync(path.join(out, 'dev'), { recursive: true });
  fs.writeFileSync(path.join(out, 'dev/index.html'), html.replace(/__STAMP__/g, stamp).replace(/__BASE__/g, '../'));
  // css = embedded fonts + game styles
  // fonts (embedded, ~90 KB) load without blocking the first paint; the boot screen needs none
  fs.writeFileSync(path.join(out, 'fonts.css'), fs.readFileSync(path.join(root, 'src/fonts.css'), 'utf8'));
  fs.writeFileSync(path.join(out, 'style.css'), fs.readFileSync(path.join(root, 'src/style.css'), 'utf8'));
  // level json copies for the editor (import/export reference)
  copyDir(path.join(root, 'src/data/levels'), path.join(out, 'data/levels'));
  console.log('built', new Date().toLocaleTimeString());
}

await buildAll();
if (watch) {
  fs.watch(path.join(root, 'src'), { recursive: true }, async () => {
    try { await buildAll(); } catch (e) { console.error(e.message); }
  });
}
